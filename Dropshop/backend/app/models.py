"""SHARED CONTRACT, the source of truth for data shapes across all layers.

Mirrored in frontend/src/types/index.ts and documented in docs/api-contract.md.
Change this file only in its own small PR, and update the TS types in the same PR.
Money is always integer cents. Datetimes are UTC.
"""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel

PurchaseStatus = Literal["monitoring", "drop_detected", "claim_pending", "claimed", "expired"]
PurchaseSource = Literal["sentient", "email", "manual", "nessie"]
ClaimStatus = Literal[
    "awaiting_approval", "submitting", "submitted", "refund_received", "rejected", "failed"
]
AgentEventKind = Literal[
    "purchase_found",
    "price_checked",
    "price_drop",
    "eligibility_checked",
    "claim_drafted",
    "claim_submitting",
    "claim_submitted",
    "refund_received",
    "vault_recorded",
    "error",
]


class PurchaseCreate(BaseModel):
    retailer: str
    product_name: str
    product_url: str | None = None
    price_paid_cents: int
    purchased_at: datetime
    order_number: str | None = None


class Purchase(PurchaseCreate):
    id: str
    user_id: str
    product_id: str  # stable key used in Tiger Data (e.g. retailer + SKU)
    source: PurchaseSource = "manual"
    nessie_purchase_id: str | None = None
    adjustment_window_ends: datetime | None = None
    current_price_cents: int | None = None
    status: PurchaseStatus = "monitoring"


class PricePoint(BaseModel):
    time: datetime
    retailer: str
    price_cents: int


class ExtractedReceipt(BaseModel):
    """Output of agents.receipt_extractor (Gemini)."""

    retailer: str
    order_number: str | None = None
    purchased_at: datetime | None = None
    items: list[PurchaseCreate] = []


class RetailerPolicy(BaseModel):
    retailer: str
    policy_url: str | None = None
    window_days: int | None = None
    conditions: list[str] = []
    summary: str = ""


class EligibilityResult(BaseModel):
    """Output of agents.eligibility (Gemini)."""

    eligible: bool
    refund_cents: int = 0
    reason: str
    policy_excerpt: str | None = None
    confidence: float = 0.0


class Claim(BaseModel):
    id: str
    user_id: str
    purchase_id: str
    retailer: str
    refund_cents: int
    status: ClaimStatus = "awaiting_approval"
    explanation: str = ""  # human-readable "why you qualify", generated by Gemini
    created_at: datetime
    submitted_at: datetime | None = None
    refund_received_at: datetime | None = None
    nessie_deposit_id: str | None = None
    solana_tx_signature: str | None = None


class AgentEvent(BaseModel):
    id: str
    user_id: str
    time: datetime
    kind: AgentEventKind
    message: str
    purchase_id: str | None = None
    claim_id: str | None = None
    screenshot_url: str | None = None


class SavingsSummary(BaseModel):
    total_recovered_cents: int
    pending_cents: int
    claims_submitted: int
    claims_won: int
    vault_address: str | None = None
    vault_balance_cents: int = 0
